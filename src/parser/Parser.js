//--  File for parsing based on the Context-Free Syntax of Haskell doc   --//

/**
 * Source : https://www.haskell.org/onlinereport/haskell2010/haskellch10.html
 * Chapter : 10.5 
 * 
 * 
 * Notational conventions :
 *  [pattern]     optional
 *  {pattern}     zero or more repetitions
 *  (pattern)     grouping
 *  pat1 | pat2   choice
 *  pat<pat′>     difference—elements generated by pat except those generated 
 *                by pat′
 *  'fibonacci'   terminal syntax in ' '
 * 
 *  BNF-like syntax is used throughout, with productions having the form:
 *  nonterm 	→ 	alt1 | alt2 | … | altn
*/

let rulesObject = new Rules(); // Haskell parsing rules
let fails = {}; // optimisation dictionnary to not try a rule we know failed
                // at a certain index in the program

let printDebug = false;
let space = 0;

/**
 * Allows to transform a list of tokens to an AST
 * @param {Program} program 
 * @returns {Boolean} true if success, false otherwise 
 */
export function parse(program){
  if (!program.isLexed){
    tokenize(program);
  }
  mainLoop(program);
  program.isParsed = true;
  return true;
}

/**
 * Tries all the rules until it finds one applicable and adds the resulting AST
 * nodes accordingly. Does this until the full list of token is parsed.
 * Nothing is returned but the program.AST is modified if success.
 * @param {Program} program 
 */
function mainLoop(program,){
  let root = mtNode("root");
  if (ruleLoop(rulesObject.rules["module"], program, root, "root")){
    program.AST = root;
  } else {
    throw Error("First rule (module) did not yield any result");
  }
  if (program.peek()){
    throw Error("Not all tokens were parsed");
  }
}

/**
 * Tests all the branches until it finds one that matches.
 * If so the tokens created by the branch will be added to the current node.
 * Otherwise, if no branch is found, returns false because the rule is not
 * applicable.
 * 
 * @param {Elem} rule 
 * @param {Program} program 
 * @param {Node} currNode 
 * @returns {Boolean}
 */
function ruleLoop(rule, program, currNode){
  if (didItFail(rule.value, program.cursor)){
    return false;
  }
  debug(2,'ruleloop', rule.value);
  for (let i = 0; i < rule.childs.length; i ++){
    let branch = rule.childs[i];
    let tmpNode = mtNode(rule.value);
    if (branchLoop(branch, program, tmpNode)){
      currNode.addChild(tmpNode);
      debug(1, 'ruleloop true', rule.value);
      return true;
    }
  }
  updateFails(rule.value, program.cursor);
  debug(4, 'ruleloop false', rule.value);  
  return false;
}

/**
 * Tests all the elements of a branch, returns true if they are all true and
 * adds the nodes to the given one (currNode) if it is the case. 
 * Otherwise returns false.
 * @param {Elem} branch 
 * @param {Program} program 
 * @param {Node} currNode 
 * @returns {Boolean}
 */
function branchLoop(branch, program, currNode){
  space += 1;
  let cursorStart = program.cursor;     // need to rollback in case of failure
  let nbChilds = currNode.childs.length;//

  let func = null;
  for (let i = 0; i < branch.childs.length; i++){
    let elem = branch.childs[i];
    if (elem[0].type === "rule"){ 
      // doesn't appear in branches but needed for root rule that is passed 
      // at the begining (module)
      func = ruleLoop;
    } else if (elem[0].type === "ref"){
      func = ruleLoop;
      elem[0] = rulesObject.rules[elem[0].value];
    } else if (elem[0].type === "data" || elem[0].type === "tokentype"){
      func = dataLoop;
    } else if (elem[0].type === "branch"){
      func = branchLoop;
    } else {
      throw new Error("Ill-formed branch, elems in branch should be either a"+
                    " rule or data, at :\n" + JSON.stringify(branch, null, 4));
    }
    if (!manageOption(elem, program, func, currNode)){
      program.cursor = cursorStart;
      currNode.childs.length = nbChilds; // truncate to delete any childs that
                                         // may have been added
                                         // FIXME : I don't believe it covers
                                         // the option 0 case (as in a branch
                                         // composed of at least 2 elements is
                                         // optional (0) and the first element
                                         // passes but not the second, manage 
                                         // option will return true so the first
                                         // element will not be removed)
      space -= 1;
      return false;
    }
  }
  space -= 1;
  return true;
}

/**
 * Verifies if a rule or data elem is valid based on it option value
 * If the rule passes, the resulting node is added to the given node (currNode)
 * elemOption is a list of the elem to try and it's option (int)
 * if the option is 4, another ref is in the list (the negation rules)
 * @param {[Elem, Int, Elem]} elemOption
 * @param {Program} program 
 * @param {function ruleFunc([Elem, Int, Elem], Program, Node) {}} ruleFunc 
 * @param {Node} currNode 
 * @returns {Boolean}
 */
function manageOption(elemOption, program, ruleFunc, currNode){
  space += 1;
  let cursorStart = program.cursor; // for rollback in case of failure
  let elem = elemOption[0];
  let option = elemOption[1];
  let passRule = ruleFunc(elem, program, currNode);
  switch (option){ 
    case 0 : // optional
      if (!passRule){
        program.cursor = cursorStart;
      }
      break;

    case 1 : // mandatory
      if (!passRule){
        program.cursor = cursorStart;
            space -= 1;
        return false;
      }
      break;

    case 2 : // at least one
      if(!passRule){
        program.cursor = cursorStart;
            space -= 1;
        return false;
      } 
      while(true){
        cursorStart = program.cursor;
        passRule = ruleFunc(elem, program, currNode);
        if (!passRule){
          program.cursor = cursorStart;
          break;
        }
      }
      break;

    case 3 : // 0 or more 
      if (!passRule){
        program.cursor = cursorStart;
      } else {
        while(true){
          cursorStart = program.cursor;
          passRule = ruleFunc(elem, program, currNode);
          if (!passRule){
            program.cursor = cursorStart;
            break;
          }
        }
      }
    break;

    case 4 : // once but not with another rule (specified)
      if (!passRule){
        program.cursor = cursorStart;
      } else {
        let cursorEnd = cursorStart; // for rollforward in case of success
        program.cursor = cursorStart;
        let passNegateRule = false;
        let mtNode = Node.mtNode("negate node");
        if (elem[2].type === "ref"){
          passNegateRule = ruleLoop(rulesObject.rules[elem[2].value], 
                                    program, mtNode);
        } else if (elem[2].type === "rule"){
          passNegateRule = ruleLoop(elem[2], program, mtNode);
        } else if (elem[2].type === "data" || elem[2].type === "tokentype"){
          passNegateRule = dataLoop(elem[2], program, mtNode);
        }
        if (passNegateRule){
            program.cursor = cursorStart;
            space -= 1;
            return false;
        } else {
          program.cursor = cursorEnd;
        }
      }
      break;

    default :
      throw new Error("Ill formed rule, option should be 0, 1, 2, 3 or 4 : " 
        + option);
  }
  space -= 1;
  return true;
}

/**
 * Verifies if a data elem is the same as the current token,
 * if so goes forward in the token list and adds the node to the current node
 * if not returns false.
 * @param {Elem} elem 
 * @param {Program} program 
 * @param {Node} currNode 
 * @returns {Boolean}
 */
function dataLoop(elem, program, currNode){
  let token = program.getToken();
  if (token === undefined) {
    return false; // FIXME : this should not happen (yet it does)
  } 
  if((elem.type === "data" && elem.value === token.value) || 
     (elem.type === "tokentype" && elem.value === token.type)){ 
    program.incCursor();
    currNode.addChild(tokenToNode(token));
    debug(3,'dataloop true', elem.value);
    return true;
  }
  debug(5,'dataloop false', elem.value + " !== " + token.value);
  return false;
}

/** 
 * Function to print in a certain color, indented according to the space
 * variable. Used in rules, branch and data functions to print the path took
 * by the parser.
 * @param {Integer} col color in which to print 
 * @param {String} text text to print 
 * @param {Boolean} val additional result to print
 */
function debug(col, text, val){
  if(printDebug){
    console.log('%s\x1b[3' + col + 'm%s\x1b[0m', " ".repeat(space), text, val);
  }
}

/**
 * update the dictionnary of rules that failed at a certain index, so that
 * we don't verify it again, useful in rules like [rule_a 'text'] rule_a.
 * We don't register 'wins' because we would need to keep track of what is
 * added where, and manage the cursor and all.
 * @param {String} ruleName 
 * @param {Integer} index 
 */
function updateFails(ruleName,index){
  fails[ruleName+index] = false;
}

/** 
 * Looks into the dictionnary fails if a rule at a certain index failed already 
 * or not, which optimises the recursive descent.
 * @param {String} ruleName 
 * @param {Integer} index 
 * @returns {Boolean}
 */
function didItFail(ruleName, index){
  return (ruleName + index) in fails;
}

