import { Program } from "../Program.js";
import { getLexeme} from "./LexerVarid.js";
import { getWhitespace } from "./LexerWhite.js";
import { addIndentation } from "./indentation.js"

//--  File for lexing based on the Lexical Syntax of Haskell doc   --//

/** 
 * Source : https://www.haskell.org/onlinereport/haskell2010/haskellch10.html
 * Chapter : 10.2 
 * 
 * How the rules were split in different files in purely arbitrary, grouping 
 * them somewhat together to avoid having one big file.
 * 
 * Notational conventions :
 *  [pattern]     optional
 *  {pattern}     zero or more repetitions
 *  (pattern)     grouping
 *  pat1 | pat2   choice
 *  pat⟨pat′⟩     difference—elements generated by pat except those generated 
 *                by pat′
 *  fibonacci     terminal syntax in typewriter font (as you can see)
 * 
 *  BNF-like syntax is used throughout, with productions having the form:
 *  nonterm 	→ 	alt1 | alt2 | … | altn
*/


export const HS_special = ["(",")",",",";","[","]","`","{","}"];

/**
 * Allows to transform the input to a list of tokens  
 * @param {Program} program 
 * @returns {Boolean}  
 */
export function tokenize(program){
  if (getProgram(program) && addIndentation(program)){
    program.isLexed = true;
    return true;
  }
  return false;
}

/**
 * Rule : program → { lexeme | whitespace } 
 * @param {Program} program
 * @returns {Boolean}
 */
function getProgram(program){
  while (getWhitespace(program) || getLexeme(program)){} 
  if (program.index === program.input.length){
    return true;
  } else if (program.index < program.input.length){
    throw Error("Not all input was parsed");
  }
  throw Error("Index > input.length");
}


/**
 * Rule : special → ( | ) | , | ; | [ | ] | ` | { | }
 * @param {Program} program 
 * @returns {Boolean} 
 */
export function getSpecial(program){
  if (HS_special.includes(program.getChar())){
    return program.addToken("Special");
  }
  return false;
}